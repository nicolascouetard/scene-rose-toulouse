  id: string;
  title: string;
  subtitle?: string;
  date: string; // YYYY-MM-DD
  endDate?: string; // Optional multi-day event
  time: string; // HHhMM
  venueId: string;
  category: GenreCategory;
  genres: string[];
  price?: string;
  status: TicketStatus;
  statusVerifiedAt?: string; // ISO timestamp from daily sync
  firstSeenAt?: string; // ISO timestamp when first discovered by sync
